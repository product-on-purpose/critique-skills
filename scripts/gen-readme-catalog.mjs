#!/usr/bin/env node
// what-it-is:   the README skill-catalog table generator
// what-it-does: reads library.json's components.skills list, reads each shipped skill's own
//               SKILL.md frontmatter (description and rubric_sources ids), and renders a markdown
//               table between two marker comments in --target (default README.md), replacing only
//               that region. --check recomputes the table and compares it against what --target
//               currently holds, exiting 1 on drift without writing anything.
// why:          S-08 (docs-and-packaging spec) requires the README's skill catalog to be generated
//               from library.json, never hand-typed, so a skill that is added, renamed, or held out
//               of a release cannot silently drift out of sync with what the README claims ships
//               (S-08 AC-4; Behavior/Examples: "a gated stretch skill fails its gate, then README's
//               catalog shows only shipped skills").
// used-by:      contributors regenerating README.md ("npm run gen:catalog"); exports
//               checkCatalogDrift()/writeCatalog() in the same shape scripts/gen-index.mjs exports
//               checkIndexDrift()/writeIndex(), so scripts/gen-plugin-manifest.mjs's aggregate
//               "npm run gen -- --check" (the CI "drift" job's entry point) can fold this generator
//               in the same way it already folds in INDEX.md, without this file needing to know
//               about that aggregator.
//
// Usage:  node scripts/gen-readme-catalog.mjs [--target=README.md] [--check]
//
// Only components.skills entries with status "active" are rendered: a skill held out of a release
// (gated stretch, failed AC-6/AC-7) is absent from library.json's active set or carries a different
// status, and the catalog must reflect that honestly rather than list every skill directory that
// happens to exist on disk.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");

const START_MARKER = "<!-- skill-catalog:start -->";
const END_MARKER = "<!-- skill-catalog:end -->";

/** Pulls the `---`-delimited frontmatter block off the top of a SKILL.md file. */
function readFrontmatter(skillMdPath) {
  const text = readFileSync(skillMdPath, "utf8");
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) {
    throw new Error(`${skillMdPath}: no --- frontmatter block found`);
  }
  return match[1];
}

/** The single-line, double-quoted `description:` value, unescaped verbatim. */
function readDescription(frontmatter, skillMdPath) {
  const match = frontmatter.match(/^description:\s*"(.*)"\s*$/m);
  if (!match) {
    throw new Error(`${skillMdPath}: no description: "..." line in frontmatter`);
  }
  return match[1];
}

/** Every `- id: <TOKEN>` line under `rubric_sources:`, in declared order. */
function readRubricIds(frontmatter) {
  return [...frontmatter.matchAll(/^\s*-\s*id:\s*(\S+)\s*$/gm)].map((m) => m[1]);
}

/** The description's lead clause, everything before " Use when...", trimmed to one sentence set. */
function readsAs(description) {
  const lead = description.split(/\s+Use when\b/i)[0].trim();
  return lead.endsWith(".") ? lead : `${lead}.`;
}

function renderRow(component, root) {
  const skillMdPath = resolve(root, component.path, "SKILL.md");
  if (!existsSync(skillMdPath)) {
    throw new Error(`${component.name}: ${skillMdPath} does not exist`);
  }
  const frontmatter = readFrontmatter(skillMdPath);
  const description = readDescription(frontmatter, skillMdPath);
  const rubricIds = readRubricIds(frontmatter);
  const reviews = readsAs(description);
  const rubric = rubricIds.length > 0 ? rubricIds.join(", ") : "n/a";
  const link = `${component.path}/SKILL.md`;
  return `| [\`${component.name}\`](${link}) | ${reviews} | ${rubric} | ${component.version} |`;
}

function renderTable(libraryJson, root) {
  const skills = (libraryJson.components?.skills ?? []).filter((s) => s.status === "active");
  if (skills.length === 0) {
    return "_No skill has shipped yet._";
  }
  const header = "| Skill | Reviews | Rubric | Version |\n|---|---|---|---|";
  const rows = skills.map((s) => renderRow(s, root));
  return [header, ...rows].join("\n");
}

function renderBlock(libraryJson, root) {
  return [
    START_MARKER,
    "<!-- Generated by `node scripts/gen-readme-catalog.mjs`. Do not edit by hand: edit " +
      "`library.json` and the relevant skill's `SKILL.md` frontmatter, then regenerate. -->",
    "",
    renderTable(libraryJson, root),
    END_MARKER,
  ].join("\n");
}

function splice(targetText, block) {
  if (!targetText.includes(START_MARKER) || !targetText.includes(END_MARKER)) {
    throw new Error(
      `${START_MARKER} / ${END_MARKER} not found in target; add the pair once before this ` +
        "command can update it",
    );
  }
  const before = targetText.split(START_MARKER)[0];
  const after = targetText.split(END_MARKER).slice(1).join(END_MARKER);
  return before + block + after;
}

function resolveTarget(targetArg) {
  return resolve(ROOT, targetArg ?? "README.md");
}

/** Diff --target's catalog block against what library.json + SKILL.md frontmatter render right now. */
export function checkCatalogDrift(targetArg) {
  const target = resolveTarget(targetArg);
  if (!existsSync(target)) {
    return { ok: false, messages: [`gen:catalog --check: target file ${target} does not exist`] };
  }
  const libraryJson = JSON.parse(readFileSync(resolve(ROOT, "library.json"), "utf8"));
  const targetText = readFileSync(target, "utf8");
  let newText;
  try {
    newText = splice(targetText, renderBlock(libraryJson, ROOT));
  } catch (e) {
    return { ok: false, messages: [`gen:catalog --check: ${e.message}`] };
  }
  if (newText !== targetText) {
    return {
      ok: false,
      messages: [
        `gen:catalog --check: ${target} skill-catalog table is out of date with library.json; ` +
          "regenerate with: npm run gen:catalog",
      ],
    };
  }
  return { ok: true, messages: [`gen:catalog --check: ${target} matches library.json + SKILL.md frontmatter.`] };
}

/** Regenerate --target's catalog block in place. */
export function writeCatalog(targetArg) {
  const target = resolveTarget(targetArg);
  if (!existsSync(target)) {
    console.error(`error: target file ${target} does not exist`);
    return 1;
  }
  const libraryJson = JSON.parse(readFileSync(resolve(ROOT, "library.json"), "utf8"));
  const targetText = readFileSync(target, "utf8");
  let newText;
  try {
    newText = splice(targetText, renderBlock(libraryJson, ROOT));
  } catch (e) {
    console.error(`error: ${e.message}`);
    return 1;
  }
  writeFileSync(target, newText, "utf8");
  console.log(`updated ${target}`);
  return 0;
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (invokedDirectly) {
  const argv = process.argv.slice(2);
  const targetArg = argv.find((a) => a.startsWith("--target="))?.slice("--target=".length);
  if (argv.includes("--check")) {
    const { ok, messages } = checkCatalogDrift(targetArg);
    for (const m of messages) console.log(m);
    process.exit(ok ? 0 : 1);
  } else {
    process.exit(writeCatalog(targetArg));
  }
}
